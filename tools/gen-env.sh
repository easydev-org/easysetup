#!/bin/bash
# gen-env.sh — write /opt/setup/env.sh from what is ACTUALLY on disk.
#
# Why it scans the directory instead of taking a list of names:
#
#   install.sh runs once per `uses:` step in a workflow. Generating env.sh from
#   "what this invocation installed" meant every call OVERWROTE the previous
#   one, so `uses: easysetup (node-22)` followed by `uses: easysetup
#   (python-3.12)` left an env.sh that knew only python and had silently dropped
#   node. Scanning /opt/setup makes the file a function of the machine, not of
#   the last command, so repeated calls accumulate instead of clobbering.
#
# It also emits one `_use_<tool>` per tool, because a flattened export cannot
# express "two versions of java are installed": JAVA_HOME holds one value. The
# default applies the alphabetically-last installed version; _use_<tool> takes
# an explicit one.
#
#   . /opt/setup/env.sh
#   _use_java 17.0.20+101      # switch without reinstalling
set -euo pipefail

OUT="${1:-/opt/setup/env.sh}"
ROOT="${EASYSETUP_ROOT:-/opt/setup}"

# Every installed setup is a directory with a .easysetup marker written by
# install.sh. That marker is what distinguishes a real install from a stray dir.
installed_ids() {
  local d b
  for d in "$ROOT"/*/; do
    [ -d "$d" ] || continue
    b=$(basename "$d")
    [ "$b" = cache ] && continue
    [ -f "$ROOT/$b/.easysetup" ] || continue
    echo "$b"
  done
}

# Key used for the function name: tool name with dashes as underscores.
key_of() {
  local tool="$1"
  case "$tool" in
    rust-toolchain-*) echo "rust_toolchain_${tool#rust-toolchain-}" ;;
    *) echo "$tool" | tr '-' '_' ;;
  esac
}

{
  echo "# generated by easysetup — do not edit, rerun install.sh instead"
  echo "# usage: . $OUT   then use the tools, or call _use_<tool> <id>"
  echo ""
  echo "_easysetup_ids() {"
  echo "  local d b"
  echo "  for d in $ROOT/*/; do"
  echo "    [ -d \"\$d\" ] || continue"
  echo "    b=\$(basename \"\$d\")"
  echo "    [ \"\$b\" = cache ] && continue"
  echo "    [ -f \"$ROOT/\$b/.easysetup\" ] || continue"
  echo "    echo \"\$b\""
  echo "  done"
  echo "}"
  echo ""
} > "$OUT"

# One _use_ function per tool. The body is chosen by what the tool needs, which
# is exactly the knowledge install.sh used to inline.
declare -A DEFAULT_ID=()
while read -r id; do
  [ -n "$id" ] || continue
  tool="${id%-*}"
  key=$(key_of "$tool")
  DEFAULT_ID["$key"]="$id"
done < <(installed_ids)

for key in $(printf '%s\n' "${!DEFAULT_ID[@]}" | sort); do
  id="${DEFAULT_ID[$key]}"
  tool="${id%-*}"
  {
    echo "_use_${key}() {"
    echo "  local arg=\"\${1:-}\""
    # Accept either a full id (`java-17.0.20+101`) or just the version
    # (`17.0.20+101`); people will type the short one.
    echo "  case \"\$arg\" in"
    echo "    \"\") id='$id' ;;"
    echo "    ${tool}-*) id=\"\$arg\" ;;"
    echo "    *) id=\"${tool}-\$arg\" ;;"
    echo "  esac"
    echo "  local d=\"$ROOT/\$id\""
    echo "  if [ ! -d \"\$d\" ]; then echo \"_use_${key}: no setup \$id\" >&2; return 1; fi"
    case "$tool" in
      java)
        echo "  export JAVA_HOME=\"\$d\"" ;;
      r)
        echo "  # R needs its bundled libicu74/libjpeg8, whose sonames trixie lacks."
        echo "  case \":\${LD_LIBRARY_PATH:-}:\" in"
        echo "    *\":\$d/lib/bundled:\"*) ;;"
        echo "    *) export LD_LIBRARY_PATH=\"\$d/lib/bundled\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}\" ;;"
        echo "  esac" ;;
      ruby)
        echo "  # libruby.so lives in the tree, and the stdlib dir is <maj>.<min>.0,"
        echo "  # which differs per version (4.0.0 vs 3.4.0) so it is discovered."
        echo "  case \":\${LD_LIBRARY_PATH:-}:\" in"
        echo "    *\":\$d/lib:\"*) ;;"
        echo "    *) export LD_LIBRARY_PATH=\"\$d/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}\" ;;"
        echo "  esac"
        echo "  local abi"
        echo "  abi=\$(ls \"\$d/lib/ruby\" 2>/dev/null | grep -E '^[0-9]+\\.[0-9]+\\.0\$' | head -1)"
        echo "  if [ -n \"\$abi\" ]; then"
        echo "    export GEM_HOME=\"\$d/lib/ruby/gems/\$abi\""
        echo "    export GEM_PATH=\"\$GEM_HOME\""
        echo "    export RUBYLIB=\"\$d/lib/ruby/\$abi:\$d/lib/ruby/\$abi/x86_64-linux\${RUBYLIB:+:\$RUBYLIB}\""
        echo "  fi" ;;
      erlang|elixir)
        echo "  # BEAM aborts on startup without a UTF-8 locale."
        echo "  export LANG=\"\${LANG:-C.UTF-8}\" LC_ALL=\"\${LC_ALL:-C.UTF-8}\"" ;;
      nix)
        echo "  # nix hard-codes /nix: its store paths and profile links are"
        echo "  # absolute. install.sh materialises the tree there, so the real"
        echo "  # commands are in the profile, not under \$d/bin."
        echo "  if [ -d /nix/var/nix/profiles/default/bin ]; then"
        echo "    PATH=\"/nix/var/nix/profiles/default/bin:\$PATH\"; export PATH"
        echo "  fi"
        echo "  # The modern CLI is off by default; a container has no nix.conf."
        echo "  export NIX_CONFIG=\"\${NIX_CONFIG:-experimental-features = nix-command flakes}\"" ;;
    esac
    echo "  PATH=\"\$d/bin:\$PATH\"; export PATH"
    echo "}"
  } >> "$OUT"
done

{
  echo ""
  echo "# Defaults: one version per tool, on PATH."
} >> "$OUT"
for key in $(printf '%s\n' "${!DEFAULT_ID[@]}" | sort); do
  echo "_use_${key}" >> "$OUT"
done

# GITHUB_PATH / GITHUB_ENV are how a GitHub Actions step passes environment to
# the NEXT step. Without this, `uses: easysetup` followed by `run: node -v` in
# a separate step would not see node at all, no matter what env.sh says.
if [ -n "${GITHUB_PATH:-}" ]; then
  while read -r id; do
    [ -d "$ROOT/$id/bin" ] && echo "$ROOT/$id/bin" >> "$GITHUB_PATH"
  done < <(installed_ids)
  echo "gen-env: appended installed bin dirs to \$GITHUB_PATH"
fi
if [ -n "${GITHUB_ENV:-}" ]; then
  echo "EASYSETUP_ENV=$OUT" >> "$GITHUB_ENV"
fi

echo "gen-env: wrote $OUT for $(installed_ids | wc -l) setup(s)"
