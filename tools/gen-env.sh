#!/bin/bash
# gen-env.sh — write $EASYSETUP_ENV from what is actually unpacked.
#
# With nix-built setups there is exactly ONE way a tool is installed, so this is
# much smaller than it used to be:
#
#   each setup unpacks a nix closure and records where its binaries live in
#   /nix/setup-root-<dir>. This reads those files and puts those directories on
#   PATH.
#
# Gone: the /opt/setup/<id>/bin assumption, and the per-tool special cases
# (JAVA_HOME, LD_LIBRARY_PATH for R's bundled libicu, GEM_HOME for ruby, the BEAM
# locale). Every one of those existed because we were hand-packaging upstream
# binaries and had to repair what a clean closure gets right by construction.
#
# It scans the registry rather than taking a list of names because install.sh runs
# once per `uses:` step: generating from "what this invocation installed" made
# each call overwrite the previous one, so a second `uses:` silently dropped the
# first tool.
#
# Usage:   . /opt/setup/env.sh        then the tools are on PATH
set -euo pipefail

OUT="${1:-${EASYSETUP_ENV:-/opt/setup/env.sh}}"
REGISTRY="${EASYSETUP_ROOT:-/nix}"

# env.sh still lives beside the old tree name. The directory is ours to create -
# nothing else does, now that setups unpack into /nix/store.
#
# On a bare runner that directory is owned by root, so creating it needs sudo.
# Same rule as install.sh: root if we are root, sudo if it exists.
OUTDIR="$(dirname "$OUT")"
if ! mkdir -p "$OUTDIR" 2>/dev/null; then
  if [ "$(id -u)" = "0" ]; then
    mkdir -p "$OUTDIR"
  elif command -v sudo >/dev/null 2>&1; then
    sudo mkdir -p "$OUTDIR"
    sudo chown "$(id -u):$(id -g)" "$OUTDIR" 2>/dev/null || true
  else
    echo "gen-env: cannot create $OUTDIR" >&2
    exit 1
  fi
fi

# One setup-root file per installed setup: "<store-path>|<dirs>".
setup_roots() {
  local f
  for f in "$REGISTRY"/setup-root-*; do
    [ -f "$f" ] || continue
    head -1 "$f"
  done
}

{
  echo "# generated by easysetup — do not edit, rerun install.sh instead"
  echo "# Every entry is a nix store path; there is no /opt/setup tree."
  echo ""
  echo "_easysetup_setup_roots() {"
  echo "  local f"
  echo "  for f in $REGISTRY/setup-root-*; do"
  echo "    [ -f \"\$f\" ] || continue"
  echo "    head -1 \"\$f\""
  echo "  done"
  echo "}"
} > "$OUT"

# Put each setup's bin dirs on PATH. No per-tool knowledge is needed: a closure
# already points at its own libraries through rpaths, so LD_LIBRARY_PATH and
# JAVA_HOME are the tool's business, not ours.
while IFS='|' read -r store dirs; do
  [ -n "$store" ] || continue
  for d in $dirs; do
    printf 'PATH="%s/%s:${PATH}"\n' "$store" "$d" >> "$OUT"
  done
done < <(setup_roots)
echo 'export PATH' >> "$OUT"

# GITHUB_PATH / GITHUB_ENV are how one Actions step passes environment to the
# NEXT step. Without this, `uses: easysetup` followed by `run: node -v` in a
# separate step would not see node at all, whatever env.sh says.
if [ -n "${GITHUB_PATH:-}" ]; then
  while IFS='|' read -r store dirs; do
    [ -n "$store" ] || continue
    for d in $dirs; do
      echo "$store/$d" >> "$GITHUB_PATH"
    done
  done < <(setup_roots)
  echo "gen-env: appended installed bin dirs to \$GITHUB_PATH"
fi
if [ -n "${GITHUB_ENV:-}" ]; then
  echo "EASYSETUP_ENV=$OUT" >> "$GITHUB_ENV"
fi

echo "gen-env: wrote $OUT for $(setup_roots | wc -l) setup(s)"
